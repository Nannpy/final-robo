"""
Lab 5 — IR Sensor + ToF  (Checkpoint 4: Robot Controlling)

ค่าตั้งทั้งหมดของแล็บอยู่ในไฟล์นี้ไฟล์เดียว เวลาอยู่หน้างานให้แก้ที่นี่
ไม่ต้องไปแก้ในโค้ดควบคุม

การติดตั้งฮาร์ดแวร์ (Class work ข้อ 1, 2, 4)
--------------------------------------------
IR 2 ตัว ต่อผ่าน Sensor Adaptor แล้วติดไว้ "ด้านข้าง" ฝั่งเดียวกัน
ตัวหนึ่งค่อนไปทางหัว อีกตัวค่อนไปทางท้าย ระยะห่างกันตามแนวยาวของหุ่น
คือ IR_BASELINE_CM ซึ่งใช้คำนวณมุมเอียงเทียบกำแพง

        หัวหุ่น
     ┌───────────┐
     │           │ ● IR_FRONT  (id, port ตาม IR_FRONT ด้านล่าง)
     │   หุ่น    │      ▲
     │           │      │ IR_BASELINE_CM
     │           │ ● IR_REAR   (id, port ตาม IR_REAR ด้านล่าง)
     └───────────┘
        ท้ายหุ่น            กำแพงอยู่ฝั่งนี้ ──►  (WALL_SIDE = "right")

ToF ตัวหน้าของหุ่น (ep_robot.sensor.sub_distance) ใช้จับกำแพงด้านหน้าเพื่อสั่งหยุด
"""

# ---------- การเชื่อมต่อ ----------
CONN_TYPE = "ap"          # "ap" = ต่อ WiFi ที่หุ่นปล่อยเอง, "sta" = หุ่นเกาะ router

# ---------- ตำแหน่ง IR บน Sensor Adaptor ----------
# รูปแบบ (board_id, port) — board_id คือเลขบอร์ด 1-8, port คือ 1 หรือ 2
#
# ผังจริงบนหุ่น (ยืนยันด้วย scan_ports.py):
#
#            หน้า
#      [1]─────────[2]      1 หน้าซ้าย  id1
#       │           │       2 หน้าขวา   id2
#       │   หุ่น    │       3 หลังซ้าย  id3   << บอร์ดนี้ port 1 เสีย ใช้ port 2
#       │           │       4 หลังขวา   id4
#      [3]─────────[4]
#            หลัง
#
# การคุมมุมต้องใช้ IR "หน้ากับหลังฝั่งเดียวกัน" เท่านั้น
# ถ้าจับคู่ผิดเป็นซ้ายกับขวา ตัวที่หันออกนอกสนามจะอ่านค่าค้าง
# แล้วการคุมมุมจะกลายเป็นการเอาระยะไปคุมมุม หุ่นจะหมุนคว้าง
IR_CHANNELS = {
    "front_left":  (1, 1),
    "rear_left":   (3, 2),   # port 1 ของบอร์ดนี้เสีย จึงใช้ port 2
    "front_right": (2, 1),
    "rear_right":  (4, 1),
}

# ระยะระหว่าง IR หน้ากับ IR หลัง วัดตามแนวยาวของหุ่น (เซนติเมตร)
# ต้องวัดจริงหลังติดตั้ง เพราะใช้คำนวณมุม: theta = atan2(front - rear, baseline)
IR_BASELINE_CM = 13.5

# กำแพงอยู่ฝั่งไหนของหุ่น: "right" หรือ "left"
WALL_SIDE = "right"

# เลือกคู่ IR ให้ตรงกับฝั่งที่กำแพงอยู่โดยอัตโนมัติ
# แก้ WALL_SIDE บรรทัดบนแล้วคู่นี้เปลี่ยนตามเอง ไม่ต้องมาแก้เลขพอร์ตซ้ำ
IR_FRONT = IR_CHANNELS[f"front_{WALL_SIDE}"]
IR_REAR  = IR_CHANNELS[f"rear_{WALL_SIDE}"]

# ---------- ToF ด้านหน้า ----------
# ToF ไม่ได้อ่านผ่าน sensor_adaptor แต่มาเป็น stream จาก sensor.sub_distance()
# ซึ่งส่งค่ามาทีเดียวสี่ช่อง (tof1-tof4) ปกติตัวที่เสียบช่องแรกคือ index 0
# ถ้าเสียบช่องอื่นให้เปลี่ยนเลขนี้ ดูได้จาก examples/14_sensor/02_tof_data.py
TOF_INDEX = 0
# ToF ติดสูงจากพื้นราว 13 ซม. กำแพงโฟมต้องสูงกว่านี้ ไม่งั้นลำแสงยิงข้ามไป
TOF_MOUNT_HEIGHT_CM = 13.0

# ---------- สมการสอบเทียบ Sharp IR ----------
# ระยะ(ซม.) = A * (adc ** B)
# ค่าเริ่มต้นเป็นค่าประมาณจากสเปค GP2Y0A21 ให้รัน calibrate_ir.py แล้ววางค่าจริงทับ
IR_CALIB = {
    "front": (4800.0, -1.05),
    "rear":  (4800.0, -1.05),
}
IR_CALIBRATED = False     # เปลี่ยนเป็น True หลังวางค่าจากการสอบเทียบจริงแล้ว

# ช่วงที่ Sharp IR เชื่อถือได้ (ซม.) — ใกล้กว่า 10 ซม. ค่าจะกลับตาลปัตร
IR_MIN_VALID_CM = 4.0
IR_MAX_VALID_CM = 80.0

# ---------- เป้าหมายของ Checkpoint 4 ----------
TARGET_WALL_CM   = 10.0   # ระยะห่างกำแพงด้านข้างที่ต้องรักษาไว้
STOP_FRONT_CM    = 5.0    # ToF เห็นกำแพงหน้าใกล้กว่านี้ = หยุด
FORWARD_SPEED    = 0.25   # m/s ความเร็วเดินหน้าระหว่างเลาะกำแพง
CONTROL_HZ       = 20     # ความถี่ของ control loop

# ---------- PID ----------
# คุมระยะห่างกำแพง: error เป็นเซนติเมตร -> ความเร็วด้านข้าง y (m/s)
PID_DISTANCE = dict(kp=0.020, ki=0.0, kd=0.004, min_output=-0.25, max_output=0.25)
# คุมมุมให้ขนานกำแพง: error เป็นองศา -> ความเร็วหมุน z (deg/s)
PID_ANGLE    = dict(kp=1.6,   ki=0.0, kd=0.12,  min_output=-60.0, max_output=60.0)

# ---------- วิธีอ่านค่า IR ----------
# True  = ใช้ stream sub_adapter() ซึ่ง push ค่าทุกช่องมาพร้อมกันถึง 50 Hz
# False = ใช้ get_adc() ถามทีละช่อง ซึ่งเป็น sync round-trip
#
# ทำไมค่าเริ่มต้นเป็น stream: get_adc() ถามทีละช่องแล้วรอคำตอบ พอยิงถี่ ๆ
# สลับหลายบอร์ด คำตอบจะชนกันจนได้ค่าหลุดเป็นเลขต่ำ ๆ (เคยเจอค่าตก 6-15 adc
# สลับกับค่าปกติ) และได้อัตราจริงแค่ราว 8 Hz ส่วน stream ไม่มี round-trip
# จึงได้ทั้งเร็วกว่าและนิ่งกว่า
USE_ADAPTER_STREAM = True
ADAPTER_FREQ_HZ = 20      # รองรับ 1, 5, 10, 20, 50

# ค่าต่ำกว่านี้ถือว่าอ่านไม่ได้ ไม่ใช่ระยะไกล — กันค่าหลุดจากบัสปนเข้ามา
ADC_MIN_VALID = 20

# ---------- การกรองสัญญาณ ----------
# หน้าต่างมัธยฐาน: กัน spike ได้ แต่หน่วงสัญญาณด้วย
# IR อัปเดตจริงราว 8-10 Hz หน้าต่าง 5 จึงหน่วงราว 250 ms ซึ่งมากพอทำให้ระบบแกว่ง
# ใช้ 3 เป็นจุดสมดุลระหว่างกัน spike กับความหน่วง
MEDIAN_WINDOW = 3         # จำนวนตัวอย่างที่เอามาหาค่ามัธยฐาน กัน spike ของ IR
POLL_INTERVAL = 0.02      # ระยะเวลาพักระหว่างรอบ poll IR (วินาที)

# ---------- การบันทึกข้อมูล ----------
LOG_DIR = "aj_sahapong/lab5/logs"
